CREATE TABLE certification_exam_schedule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    certification_code VARCHAR(32) NOT NULL,
    exam_year INTEGER NOT NULL CHECK (exam_year BETWEEN 2020 AND 2100),
    round_number INTEGER NOT NULL CHECK (round_number BETWEEN 1 AND 9999),
    exam_stage VARCHAR(32) NOT NULL CHECK (CASE exam_stage WHEN 'WRITTEN' THEN 1 WHEN 'PRACTICAL' THEN 1 WHEN 'FIRST' THEN 1 WHEN 'SECOND' THEN 1 WHEN 'SINGLE' THEN 1 ELSE 0 END = 1),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    source_url VARCHAR(2000) NOT NULL CHECK (length(trim(source_url)) > 0),
    checked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    FOREIGN KEY (certification_code) REFERENCES certification(code) ON DELETE RESTRICT,
    UNIQUE (certification_code, exam_year, round_number, exam_stage),
    CHECK (starts_on <= ends_on),
    CHECK (EXTRACT(YEAR FROM starts_on) = exam_year)
);
CREATE INDEX idx_certification_exam_schedule_dates ON certification_exam_schedule(certification_code, starts_on, ends_on);
