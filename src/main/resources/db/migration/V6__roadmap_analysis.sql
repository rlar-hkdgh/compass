-- Additive storage only. No AI calls, APIs or existing data conversion.
CREATE TABLE evaluation_category (
    code VARCHAR(32) NOT NULL,
    name VARCHAR(100) NOT NULL,
    display_order INTEGER NOT NULL,
    PRIMARY KEY(code),
    UNIQUE(display_order)
);

CREATE TABLE evaluation_policy (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    version INTEGER NOT NULL,
    name VARCHAR(100) NOT NULL,
    effective_from TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(id),
    UNIQUE(version),
    UNIQUE(effective_from),
    CHECK(version>0)
);

CREATE TABLE evaluation_policy_weight (
    policy_id BIGINT NOT NULL,
    FOREIGN KEY(policy_id) REFERENCES evaluation_policy(id),
    category_code VARCHAR(32) NOT NULL,
    FOREIGN KEY(category_code) REFERENCES evaluation_category(code),
    weight INTEGER NOT NULL,
    PRIMARY KEY(policy_id,category_code),
    CHECK(weight BETWEEN 0 AND 100)
);

CREATE TABLE posting_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    source_code VARCHAR(32) NOT NULL,
    source_posting_id VARCHAR(64) NOT NULL,
    input_hash VARCHAR(64) NOT NULL,
    input_snapshot JSONB NOT NULL,
    status VARCHAR(32) NOT NULL,
    summary TEXT,
    error_code VARCHAR(64),
    attempt_count INTEGER NOT NULL DEFAULT 1,
    retry_after TIMESTAMP WITH TIME ZONE,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY(id),
    FOREIGN KEY(source_code,source_posting_id) REFERENCES job_posting(source_code,source_posting_id),
    UNIQUE(source_code,source_posting_id,input_hash),
    CHECK((status='PROCESSING' OR status='SUCCESS' OR status='FAILED')),
    CHECK(attempt_count>=1)
);

CREATE TABLE posting_analysis_requirement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    posting_analysis_id BIGINT NOT NULL,
    FOREIGN KEY(posting_analysis_id) REFERENCES posting_analysis(id),
    category_code VARCHAR(32) NOT NULL,
    FOREIGN KEY(category_code) REFERENCES evaluation_category(code),
    name VARCHAR(255) NOT NULL,
    requirement_type VARCHAR(32) NOT NULL,
    description TEXT,
    evidence_text TEXT NOT NULL,
    display_order INTEGER NOT NULL,
    PRIMARY KEY(id),
    CHECK((requirement_type='REQUIRED' OR requirement_type='PREFERRED' OR requirement_type='UNSPECIFIED'))
);

CREATE TABLE gap_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    student_id BIGINT NOT NULL,
    FOREIGN KEY(student_id) REFERENCES student(id),
    posting_analysis_id BIGINT NOT NULL,
    FOREIGN KEY(posting_analysis_id) REFERENCES posting_analysis(id),
    evaluation_policy_id BIGINT NOT NULL,
    FOREIGN KEY(evaluation_policy_id) REFERENCES evaluation_policy(id),
    student_input_hash VARCHAR(64) NOT NULL,
    student_input_snapshot JSONB NOT NULL,
    status VARCHAR(32) NOT NULL,
    overall_score NUMERIC,
    summary TEXT,
    error_code VARCHAR(64),
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY(id),
    CHECK((status='PROCESSING' OR status='SUCCESS' OR status='FAILED'))
);

CREATE TABLE gap_analysis_category (
    gap_analysis_id BIGINT NOT NULL,
    FOREIGN KEY(gap_analysis_id) REFERENCES gap_analysis(id),
    category_code VARCHAR(32) NOT NULL,
    FOREIGN KEY(category_code) REFERENCES evaluation_category(code),
    current_score NUMERIC,
    required_score NUMERIC,
    assessment_status VARCHAR(32) NOT NULL,
    explanation TEXT NOT NULL,
    missing_information TEXT,
    PRIMARY KEY(gap_analysis_id,category_code),
    CHECK((assessment_status='MET' OR assessment_status='PARTIALLY_MET' OR assessment_status='NOT_MET' OR assessment_status='UNASSESSABLE')),
    CHECK(length(trim(explanation))>0)
);

CREATE TABLE career_roadmap (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    student_id BIGINT NOT NULL,
    FOREIGN KEY(student_id) REFERENCES student(id),
    source_code VARCHAR(32) NOT NULL,
    source_posting_id VARCHAR(64) NOT NULL,
    gap_analysis_id BIGINT NOT NULL,
    FOREIGN KEY(gap_analysis_id) REFERENCES gap_analysis(id),
    name VARCHAR(255) NOT NULL,
    summary TEXT,
    generation_status VARCHAR(32) NOT NULL,
    error_code VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(id),
    FOREIGN KEY(source_code,source_posting_id) REFERENCES job_posting(source_code,source_posting_id),
    UNIQUE(id,student_id,source_code,source_posting_id),
    CHECK((generation_status='PROCESSING' OR generation_status='SUCCESS' OR generation_status='FAILED'))
);

CREATE TABLE student_active_roadmap (
    student_id BIGINT NOT NULL,
    FOREIGN KEY(student_id) REFERENCES student(id),
    source_code VARCHAR(32) NOT NULL,
    source_posting_id VARCHAR(64) NOT NULL,
    career_roadmap_id BIGINT NOT NULL,
    activated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(student_id,source_code,source_posting_id),
    FOREIGN KEY(source_code,source_posting_id) REFERENCES job_posting(source_code,source_posting_id),
    FOREIGN KEY(career_roadmap_id,student_id,source_code,source_posting_id) REFERENCES career_roadmap(id,student_id,source_code,source_posting_id)
);

CREATE TABLE roadmap_period (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    career_roadmap_id BIGINT NOT NULL,
    FOREIGN KEY(career_roadmap_id) REFERENCES career_roadmap(id),
    academic_year INTEGER NOT NULL,
    period_type VARCHAR(32) NOT NULL,
    summary TEXT,
    display_order INTEGER NOT NULL,
    PRIMARY KEY(id),
    UNIQUE(career_roadmap_id,academic_year,period_type),
    UNIQUE(career_roadmap_id,display_order),
    CHECK((period_type='FIRST_SEMESTER' OR period_type='SUMMER_BREAK' OR period_type='SECOND_SEMESTER' OR period_type='WINTER_BREAK'))
);

CREATE TABLE roadmap_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    roadmap_period_id BIGINT NOT NULL,
    FOREIGN KEY(roadmap_period_id) REFERENCES roadmap_period(id),
    title VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    recommendation_reason TEXT NOT NULL,
    activity_type VARCHAR(32) NOT NULL,
    resource_url VARCHAR(2000),
    planned_start_on DATE,
    planned_end_on DATE,
    display_order INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL,
    completed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(id),
    UNIQUE(roadmap_period_id,display_order),
    CHECK(planned_start_on IS NULL OR planned_end_on IS NULL OR planned_start_on<=planned_end_on),
    CHECK((status='TODO' OR status='IN_PROGRESS' OR status='COMPLETED')),
    CHECK((status='COMPLETED' AND completed_at IS NOT NULL) OR (status<>'COMPLETED' AND completed_at IS NULL)),
    CHECK((activity_type='COURSE' OR activity_type='PROJECT' OR activity_type='CERTIFICATION' OR activity_type='INTERNSHIP' OR activity_type='EXTRACURRICULAR' OR activity_type='BOOTCAMP' OR activity_type='OTHER'))
);

CREATE TABLE roadmap_task_category (
    task_id BIGINT NOT NULL,
    FOREIGN KEY(task_id) REFERENCES roadmap_task(id),
    category_code VARCHAR(32) NOT NULL,
    FOREIGN KEY(category_code) REFERENCES evaluation_category(code),
    expected_score_gain NUMERIC,
    explanation TEXT NOT NULL,
    PRIMARY KEY(task_id,category_code),
    CHECK(expected_score_gain>=0),
    CHECK(length(trim(explanation))>0)
);

