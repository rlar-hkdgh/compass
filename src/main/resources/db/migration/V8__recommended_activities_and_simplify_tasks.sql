CREATE TABLE activity_type (
    code VARCHAR(32) NOT NULL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    display_order INTEGER NOT NULL,
    UNIQUE(display_order)
);

CREATE TABLE activity_source (
    code VARCHAR(32) NOT NULL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    base_url VARCHAR(2000),
    is_active BOOLEAN NOT NULL
);

CREATE TABLE career_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    activity_type_code VARCHAR(32) NOT NULL,
    FOREIGN KEY(activity_type_code) REFERENCES activity_type(code) ON DELETE RESTRICT,
    source_code VARCHAR(32) NOT NULL,
    FOREIGN KEY(source_code) REFERENCES activity_source(code) ON DELETE RESTRICT,
    source_activity_id TEXT,
    name VARCHAR(500) NOT NULL,
    provider_name VARCHAR(255) NOT NULL,
    description TEXT NOT NULL,
    eligibility_text TEXT,
    raw_content TEXT,
    source_url VARCHAR(2000),
    source_metadata JSONB,
    application_start_at TIMESTAMP WITH TIME ZONE,
    application_end_at TIMESTAMP WITH TIME ZONE,
    starts_on DATE,
    ends_on DATE,
    location_text TEXT,
    delivery_mode VARCHAR(32) NOT NULL,
    availability_status VARCHAR(32) NOT NULL,
    is_active BOOLEAN NOT NULL,
    last_collected_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE(source_code,source_activity_id),
    UNIQUE(id,activity_type_code),
    CHECK(activity_type_code='COURSE' OR activity_type_code='CERTIFICATION' OR activity_type_code='EXTRACURRICULAR' OR activity_type_code='INTERNSHIP' OR activity_type_code='BOOTCAMP'),
    CHECK(delivery_mode='ONLINE' OR delivery_mode='OFFLINE' OR delivery_mode='HYBRID' OR delivery_mode='UNKNOWN'),
    CHECK(availability_status='AVAILABLE' OR availability_status='RECRUITING' OR availability_status='CLOSED' OR availability_status='CANCELLED' OR availability_status='UNKNOWN'),
    CHECK(source_code='MANUAL' OR (source_activity_id IS NOT NULL AND length(trim(source_activity_id))>0)),
    CHECK(application_start_at IS NULL OR application_end_at IS NULL OR application_start_at<=application_end_at),
    CHECK(starts_on IS NULL OR ends_on IS NULL OR starts_on<=ends_on)
);

CREATE TABLE course_activity (
    activity_id BIGINT NOT NULL PRIMARY KEY,
    FOREIGN KEY(activity_id) REFERENCES career_activity(id) ON DELETE RESTRICT,
    course_number VARCHAR(32) NOT NULL,
    academic_year INTEGER NOT NULL,
    semester VARCHAR(32) NOT NULL,
    section_number VARCHAR(32),
    department_code VARCHAR(32),
    department_name VARCHAR(255),
    credits NUMERIC,
    completion_type_text VARCHAR(100),
    professor_name VARCHAR(255),
    syllabus_text TEXT,
    syllabus_url VARCHAR(2000)
);

CREATE TABLE certification_activity (
    activity_id BIGINT NOT NULL PRIMARY KEY,
    FOREIGN KEY(activity_id) REFERENCES career_activity(id) ON DELETE RESTRICT,
    certification_code VARCHAR(32) NOT NULL,
    FOREIGN KEY(certification_code) REFERENCES certification(code) ON DELETE RESTRICT,
    qualification_type_text VARCHAR(100),
    exam_content TEXT,
    preparation_text TEXT,
    fee_text TEXT
);

CREATE TABLE extracurricular_activity (
    activity_id BIGINT NOT NULL PRIMARY KEY,
    FOREIGN KEY(activity_id) REFERENCES career_activity(id) ON DELETE RESTRICT,
    program_id VARCHAR(128) NOT NULL,
    round_name VARCHAR(100),
    mileage_points INTEGER,
    completion_condition TEXT,
    capacity INTEGER
);

CREATE TABLE internship_activity (
    activity_id BIGINT NOT NULL PRIMARY KEY,
    FOREIGN KEY(activity_id) REFERENCES career_activity(id) ON DELETE RESTRICT,
    company_name VARCHAR(255) NOT NULL,
    company_id BIGINT,
    FOREIGN KEY(company_id) REFERENCES company(id) ON DELETE RESTRICT,
    internship_type_text VARCHAR(100),
    job_description TEXT,
    practice_content TEXT,
    required_skill_text TEXT,
    weekly_hours NUMERIC,
    credit_linked BOOLEAN,
    compensation_text TEXT,
    application_method TEXT
);

CREATE TABLE bootcamp_activity (
    activity_id BIGINT NOT NULL PRIMARY KEY,
    FOREIGN KEY(activity_id) REFERENCES career_activity(id) ON DELETE RESTRICT,
    program_name VARCHAR(255),
    cohort_name VARCHAR(100),
    training_type_text VARCHAR(100),
    total_hours NUMERIC,
    curriculum_text TEXT,
    prerequisite_text TEXT,
    tuition_text TEXT,
    support_text TEXT,
    selection_process TEXT
);

