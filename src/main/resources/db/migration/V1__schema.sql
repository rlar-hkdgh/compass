    CONSTRAINT chk_student_login_format CHECK ((((char_length((login_id)) >= 4) AND (char_length((login_id)) <= 20)) AND ((login_id) = lower((login_id))))),
    CONSTRAINT student_check CHECK ((((expected_graduation_year IS NULL) AND (expected_graduation_month IS NULL)) OR ((expected_graduation_year IS NOT NULL) AND ((expected_graduation_month >= 1) AND (expected_graduation_month <= 12)) AND (expected_graduation_month IS NOT NULL))))
