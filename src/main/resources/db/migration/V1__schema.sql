CREATE TABLE job_posting (
    source_code character varying(32) NOT NULL,
    source_posting_id character varying(512) NOT NULL,
    company_id bigint NOT NULL,
    title character varying(500) NOT NULL,
    source_url character varying(2000) NOT NULL,
    active boolean NOT NULL,
    application_start_at timestamp with time zone,
    application_end_at timestamp with time zone,
    keywords text,
    description text,
    education_level_code character varying(32),
    deadline_type_code character varying(32),
    experience_type_code character varying(32),
    source_metadata text,
    education_note text,
    salary_unit_code character varying(32),
    salary_decision_code character varying(32),
    salary_min_amount bigint,
    salary_max_amount bigint,
    CONSTRAINT chk_salary_amount_codes CHECK ((((salary_min_amount IS NULL) AND (salary_max_amount IS NULL)) OR ((salary_unit_code IS NOT NULL) AND (salary_decision_code IS NOT NULL) AND ((salary_decision_code) = 'DISCLOSED')))),
    CONSTRAINT chk_salary_amount_range CHECK (((salary_min_amount IS NULL) OR (salary_max_amount IS NULL) OR (salary_min_amount <= salary_max_amount))),
    CONSTRAINT chk_salary_disclosed_amount CHECK (((salary_decision_code IS NULL) OR ((salary_decision_code) <> 'DISCLOSED') OR (salary_min_amount IS NOT NULL) OR (salary_max_amount IS NOT NULL))),
    CONSTRAINT chk_salary_max_nonnegative CHECK (((salary_max_amount IS NULL) OR (salary_max_amount >= 0))),
    CONSTRAINT chk_salary_min_nonnegative CHECK (((salary_min_amount IS NULL) OR (salary_min_amount >= 0))),
    CONSTRAINT job_posting_check1 CHECK (((application_start_at IS NULL) OR (application_end_at IS NULL) OR (application_start_at <= application_end_at)))
);

