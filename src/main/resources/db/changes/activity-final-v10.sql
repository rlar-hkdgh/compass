CREATE TABLE course_activity_v10 (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_number VARCHAR(32) NOT NULL,
 academic_year INTEGER NOT NULL,
 semester VARCHAR(32) NOT NULL,
 section_number VARCHAR(32),
 name VARCHAR(500) NOT NULL,
 department_code VARCHAR(32),
 department_name VARCHAR(255),
 credits NUMERIC,
 description TEXT NOT NULL,
 source_url VARCHAR(2000),
 UNIQUE(academic_year,semester,course_number,section_number,department_code)
);
CREATE TABLE career_activity_v10 (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 activity_type_code VARCHAR(32) NOT NULL REFERENCES activity_type(code) ON DELETE RESTRICT,
 source_code VARCHAR(32) NOT NULL REFERENCES activity_source(code) ON DELETE RESTRICT,
 source_activity_id TEXT,
 name VARCHAR(500) NOT NULL,
 provider_name VARCHAR(255) NOT NULL,
 description TEXT NOT NULL,
 source_url VARCHAR(2000),
 application_start_at TIMESTAMP WITH TIME ZONE,
 application_end_at TIMESTAMP WITH TIME ZONE,
 starts_on DATE,
 ends_on DATE,
 UNIQUE(source_code,source_activity_id),
 CHECK(CASE activity_type_code WHEN 'EXTRACURRICULAR' THEN 1 WHEN 'INTERNSHIP' THEN 1 WHEN 'BOOTCAMP' THEN 1 ELSE 0 END=1),
 CHECK(source_code='MANUAL' OR (source_activity_id IS NOT NULL AND length(trim(source_activity_id))>0)),
 CHECK(application_start_at IS NULL OR application_end_at IS NULL OR application_start_at<=application_end_at),
 CHECK(starts_on IS NULL OR ends_on IS NULL OR starts_on<=ends_on)
);
CREATE TABLE recommended_task (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL REFERENCES student(id) ON DELETE RESTRICT,
 gap_analysis_id BIGINT NOT NULL,
 course_activity_id BIGINT REFERENCES course_activity_v10(id) ON DELETE RESTRICT,
 career_activity_id BIGINT REFERENCES career_activity_v10(id) ON DELETE RESTRICT,
 certification_code VARCHAR(32) REFERENCES certification(code) ON DELETE RESTRICT,
 certification_exam_schedule_id BIGINT,
 title VARCHAR(255) NOT NULL,
 description TEXT NOT NULL,
 academic_year INTEGER NOT NULL,
 period_type VARCHAR(32) NOT NULL,
 display_order INTEGER NOT NULL CHECK(display_order>=0),
 status VARCHAR(32) NOT NULL,
 completed_at TIMESTAMP WITH TIME ZONE,
 FOREIGN KEY(gap_analysis_id,student_id) REFERENCES gap_analysis(id,student_id) ON DELETE RESTRICT,
 FOREIGN KEY(certification_exam_schedule_id,certification_code) REFERENCES certification_exam_schedule(id,certification_code) ON DELETE RESTRICT,
 UNIQUE(student_id,academic_year,period_type,display_order),
 CHECK(CASE period_type WHEN 'FIRST_SEMESTER' THEN 1 WHEN 'SUMMER_BREAK' THEN 1 WHEN 'SECOND_SEMESTER' THEN 1 WHEN 'WINTER_BREAK' THEN 1 ELSE 0 END=1),
 CHECK(CASE status WHEN 'TODO' THEN 1 WHEN 'IN_PROGRESS' THEN 1 WHEN 'COMPLETED' THEN 1 ELSE 0 END=1),
 CHECK((status='COMPLETED' AND completed_at IS NOT NULL) OR (status<>'COMPLETED' AND completed_at IS NULL)),
 CHECK((CASE WHEN course_activity_id IS NULL THEN 0 ELSE 1 END)+(CASE WHEN career_activity_id IS NULL THEN 0 ELSE 1 END)+(CASE WHEN certification_code IS NULL THEN 0 ELSE 1 END)<=1),
 CHECK(certification_exam_schedule_id IS NULL OR certification_code IS NOT NULL)
);
